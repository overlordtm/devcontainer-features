#!/usr/bin/env bash
# shellcheck disable=SC2016 # rc lines expand $HOME when the user's shell runs them.
set -euo pipefail

FEATURE_ID="shell-history"
VOLUME_DIR="/dc/shell-history"
SCRIPTS_DIR="/usr/local/share/${FEATURE_ID}"
HISTORY_SIZE="${HISTORYSIZE:-10000}"

if [ "$(id -u)" -ne 0 ]; then
    echo "Script must be run as root. Use sudo, su, or add \"USER root\" to your Dockerfile before running this script." >&2
    exit 1
fi

case "${HISTORY_SIZE}" in
    '' | *[!0-9]*)
        echo "Invalid historySize '${HISTORY_SIZE}', falling back to 10000." >&2
        HISTORY_SIZE="10000"
        ;;
esac
if [ "${HISTORY_SIZE}" -lt 1 ]; then
    echo "Invalid historySize '${HISTORY_SIZE}', falling back to 10000." >&2
    HISTORY_SIZE="10000"
fi

USER_NAME="${_REMOTE_USER:-root}"
USER_HOME="${_REMOTE_USER_HOME:-}"
if [ -z "${USER_HOME}" ]; then
    USER_HOME="$(getent passwd "${USER_NAME}" 2>/dev/null | cut -d: -f6 || true)"
fi
if [ -z "${USER_HOME}" ]; then
    USER_HOME="/root"
fi

echo "Setting up ${FEATURE_ID} for ${USER_NAME} (${USER_HOME})..."

# Docker copies the ownership of the mount point into a fresh named volume the
# first time it is used, so create the directory as the remote user.
mkdir -p "${VOLUME_DIR}"
chown "${USER_NAME}" "${VOLUME_DIR}"
# Shell history can contain secrets, so keep the volume private to its owner.
chmod 0700 "${VOLUME_DIR}"

# Create directories below the user's home as the remote user, fixing up any
# root-owned components created by this script.
ensure_user_dir() {
    local dir="$1"
    mkdir -p "${dir}"

    local current="${dir}"
    while [ "${current}" != "${USER_HOME}" ] && [ "${current}" != "/" ] && [ "${current}" != "." ]; do
        if [ "$(stat -c '%u' "${current}" 2>/dev/null || echo 0)" = "0" ]; then
            chown "${USER_NAME}" "${current}"
        fi
        current="$(dirname "${current}")"
    done
}

ensure_trailing_newline() {
    local file="$1"

    [ -s "${file}" ] || return 0
    if [ "$(tail -c 1 "${file}" | wc -l)" -eq 0 ]; then
        printf '\n' >> "${file}"
    fi
}

# Add the source line to a shell's rc file only once. The generated files under
# ~/.config/shell-history can then be rewritten on every image rebuild.
add_rc_lines() {
    local file="$1"
    local needle="$2"
    shift 2
    local created=0

    ensure_user_dir "$(dirname "${file}")"
    if [ ! -e "${file}" ]; then
        created=1
    fi
    touch "${file}"

    if ! grep -qF "${needle}" "${file}" 2>/dev/null; then
        ensure_trailing_newline "${file}"
        printf '%s\n' "$@" >> "${file}"
        echo "Added shell history configuration to ${file}"
    fi

    if [ "${created}" -eq 1 ]; then
        chown "${USER_NAME}" "${file}"
    fi
}

CONFIG_DIR="${USER_HOME}/.config/shell-history"
ensure_user_dir "${CONFIG_DIR}"

cat > "${CONFIG_DIR}/bash.sh" <<EOF
# Generated by the ${FEATURE_ID} devcontainer feature. Do not edit.
export HISTFILE="${VOLUME_DIR}/.bash_history"
HISTSIZE=${HISTORY_SIZE}
HISTFILESIZE=${HISTORY_SIZE}
EOF
cat >> "${CONFIG_DIR}/bash.sh" <<'EOF'
# Append instead of overwriting the history file when the shell exits.
shopt -s histappend
# Append each command as it runs so history survives an abrupt container stop.
case "${PROMPT_COMMAND-}" in
    *"history -a"*) ;;
    *) PROMPT_COMMAND="history -a${PROMPT_COMMAND:+; ${PROMPT_COMMAND}}" ;;
esac
EOF

cat > "${CONFIG_DIR}/zsh.sh" <<EOF
# Generated by the ${FEATURE_ID} devcontainer feature. Do not edit.
export HISTFILE="${VOLUME_DIR}/.zsh_history"
HISTSIZE=${HISTORY_SIZE}
SAVEHIST=${HISTORY_SIZE}
EOF
cat >> "${CONFIG_DIR}/zsh.sh" <<'EOF'
# Write commands as they run instead of only when the shell exits.
setopt INC_APPEND_HISTORY
EOF

cat > "${CONFIG_DIR}/config.fish" <<EOF
# Generated by the ${FEATURE_ID} devcontainer feature. Do not edit.
set -l shell_history_volume "${VOLUME_DIR}"
EOF
cat >> "${CONFIG_DIR}/config.fish" <<'EOF'
set -l shell_history_dir "$HOME/.local/share/fish"
if set -q XDG_DATA_HOME; and test -n "$XDG_DATA_HOME"
    set shell_history_dir "$XDG_DATA_HOME/fish"
end
mkdir -p "$shell_history_dir"
set -l shell_history_file "$shell_history_dir/fish_history"
if not test -L "$shell_history_file"
    if test -f "$shell_history_file"
        cat "$shell_history_file" >> "$shell_history_volume/fish_history"
        rm -f "$shell_history_file"
    end
    ln -sf "$shell_history_volume/fish_history" "$shell_history_file"
end
EOF

chown "${USER_NAME}" "${CONFIG_DIR}/bash.sh" "${CONFIG_DIR}/zsh.sh" "${CONFIG_DIR}/config.fish"

add_rc_lines "${USER_HOME}/.bashrc" ".config/shell-history/bash.sh" \
    '# shell-history (devcontainer feature)' \
    '[ -f "$HOME/.config/shell-history/bash.sh" ] && . "$HOME/.config/shell-history/bash.sh"'

add_rc_lines "${USER_HOME}/.zshrc" ".config/shell-history/zsh.sh" \
    '# shell-history (devcontainer feature)' \
    '[ -f "$HOME/.config/shell-history/zsh.sh" ] && . "$HOME/.config/shell-history/zsh.sh"'

add_rc_lines "${USER_HOME}/.config/fish/config.fish" ".config/shell-history/config.fish" \
    '# shell-history (devcontainer feature)' \
    'if test -f "$HOME/.config/shell-history/config.fish"' \
    '    source "$HOME/.config/shell-history/config.fish"' \
    'end'

# Point fish at the volume. If the image already has a fish history file, leave
# it in place and let onCreate.sh import it before creating the link.
FISH_DATA_DIR="${USER_HOME}/.local/share/fish"
FISH_HISTORY="${FISH_DATA_DIR}/fish_history"
ensure_user_dir "${FISH_DATA_DIR}"
if [ -f "${FISH_HISTORY}" ] && [ ! -L "${FISH_HISTORY}" ]; then
    echo "Existing ${FISH_HISTORY} will be imported into ${VOLUME_DIR} on first container creation"
else
    ln -sfn "${VOLUME_DIR}/fish_history" "${FISH_HISTORY}"
    chown -h "${USER_NAME}" "${FISH_HISTORY}"
fi

# Lifecycle script. Runs after the volume is mounted so it can repair volume
# ownership, import existing history, and repair the fish history link.
mkdir -p "${SCRIPTS_DIR}"
cp "$(dirname "$0")/oncreate.sh" "${SCRIPTS_DIR}/oncreate.sh"
chmod 0755 "${SCRIPTS_DIR}/oncreate.sh"

echo "Finished installing ${FEATURE_ID}"
